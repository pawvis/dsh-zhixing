function hashDate(date) {
  let h = 0
  for (const char of String(date)) h = (h * 31 + char.charCodeAt(0)) % 2_147_483_647
  return h
}

export function quoteOfDay(date, all) {
  const list = all?.length ? all : DEFAULT_QUOTES.map((row) => ({ text: row[0], author: row[1], source: row[2] }))
  if (!list.length) return null
  const [y, m, d] = String(date).split('-').map(Number)
  const day = Math.floor(Date.UTC(y, m - 1, d) / 86_400_000)
  const index = ((day % list.length) + list.length) % list.length
  return { ...list[index], index, total: list.length }
}

export async function readCustomQuotes(store) {
  const file = store.p('语录', '语录.json')
  try {
    const data = JSON.parse(await fs.readFile(file, 'utf8'))
    return Array.isArray(data.items) ? data.items : []
  } catch { return [] }
}

export async function writeCustomQuotes(store, items) {
  const dir = store.p('语录')
  await fs.mkdir(dir, { recursive: true })
  const file = path.join(dir, '语录.json')
  await fs.writeFile(file, `${JSON.stringify({ version: 1, items }, null, 2)}\n`, 'utf8')
  return file
}

export function defaultsAsItems() {
  return DEFAULT_QUOTES.map((row, index) => ({ id: `d-${index}`, text: row[0], author: row[1], source: row[2], builtin: true }))
}
